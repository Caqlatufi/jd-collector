import {expect, test} from './native/harness.mjs';

test('部署时间表：真实亚数日期、灰色拒绝与超时、节点弹窗（只读）',async({page})=>{
  await page.setViewportSize({width:1600,height:1100});
  const before=await (await page.request.get('api/postings/123')).json();
  expect(before.result.appliedAt).toBe('2026-10-13T00:00:00');
  const snapshot=await (await page.request.get('api/dashboard/today')).json();
  const rejected=snapshot.result.planItems.find((i:any)=>i.title==='被拒');
  const timeout=snapshot.result.planItems.find((i:any)=>i.status==='TIMED_OUT');
  expect(rejected.status).toBe('ENDED');expect(timeout).toBeTruthy();
  await page.goto('./?postingId=123');
  await expect(page.locator('.top-navigation')).not.toContainText('面试记录');
  await page.locator('[data-plan-id="application-123"]').click();
  const dialog=page.getByRole('dialog');
  await expect(dialog.getByRole('button',{name:'保存进度',exact:true})).toBeEnabled();
  await expect.poll(()=>dialog.evaluate(el=>getComputedStyle(el).transform)).toBe('none');
  await expect(dialog).toContainText('亚数');
  await dialog.getByText('修改本条记录',{exact:true}).click();
  await expect(dialog.locator('.el-date-editor input')).toHaveValue('2026-10-13 00:00:00');
  await page.screenshot({path:'test-results/timeline-live-dialog.png'});
  await dialog.getByRole('button',{name:'关闭',exact:true}).click();
  await expect(page.locator(`[data-plan-id="${rejected.id}"]`)).toHaveCount(0);
  await expect(page.locator(`[data-plan-id="${timeout.id}"]`)).toHaveCount(0);
  await page.locator('.progress-type-filter .el-select__wrapper').click();
  await expect(page.locator('.el-zoom-in-top-enter-active,.el-zoom-in-top-leave-active')).toHaveCount(0);
  await expect(page.getByRole('option',{name:'被拒',exact:true})).toBeVisible();
  await page.getByRole('option',{name:'被拒',exact:true}).click();
  const rejectedBlock=page.locator(`[data-plan-id="${rejected.id}"]`);
  await expect(rejectedBlock).toHaveCSS('background-color','rgb(123, 133, 126)');
  await page.locator('.progress-type-filter .el-select__wrapper').click();
  await expect(page.locator('.el-zoom-in-top-enter-active,.el-zoom-in-top-leave-active')).toHaveCount(0);
  await expect(page.getByRole('option',{name:'超时',exact:true})).toBeVisible();
  await page.getByRole('option',{name:'超时',exact:true}).click();
  await expect(page.locator(`[data-plan-id="${timeout.id}"]`).first()).toHaveCSS('background-color','rgb(123, 133, 126)');
  await page.screenshot({path:'test-results/timeline-live-1600.png',fullPage:true});
  await page.setViewportSize({width:720,height:1100});
  await expect.poll(()=>page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
  await page.screenshot({path:'test-results/timeline-live-720.png',fullPage:true});
  const after=await (await page.request.get('api/postings/123')).json();
  expect(after).toEqual(before);
});
